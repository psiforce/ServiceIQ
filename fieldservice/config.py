"""Field-service platform settings (read from the environment and the project .env file)."""
from functools import lru_cache
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

PROJECT_ROOT = Path(__file__).resolve().parent.parent


class FSPSettings(BaseSettings):
    model_config = SettingsConfigDict(env_file=PROJECT_ROOT / ".env", env_file_encoding="utf-8", extra="ignore")

    # A separate database from ServiceIQ's, so the two systems stay independent
    fsp_database_url: str = f"sqlite:///{(PROJECT_ROOT / 'var' / 'fieldservice.db').as_posix()}"
    # JSON {"org_id": "key"} supplied in the cloud (Secret Manager); locally keys are generated by `seed`
    fsp_api_keys: str = ""
    data_dir: Path = PROJECT_ROOT / "data"


@lru_cache
def get_fsp_settings() -> FSPSettings:
    return FSPSettings()
